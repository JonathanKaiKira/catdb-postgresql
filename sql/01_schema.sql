BEGIN;

CREATE SCHEMA inventory_sales;
SET LOCAL search_path TO inventory_sales, pg_catalog;

CREATE TABLE customers (
    customer_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    email text NOT NULL UNIQUE CHECK (btrim(email) <> ''),
    full_name text NOT NULL CHECK (btrim(full_name) <> '')
);

CREATE TABLE suppliers (
    supplier_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    supplier_code text NOT NULL UNIQUE CHECK (btrim(supplier_code) <> ''),
    name text NOT NULL CHECK (btrim(name) <> '')
);

CREATE TABLE categories (
    category_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name text NOT NULL UNIQUE CHECK (btrim(name) <> '')
);

CREATE TABLE products (
    product_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    sku text NOT NULL UNIQUE CHECK (btrim(sku) <> ''),
    name text NOT NULL CHECK (btrim(name) <> ''),
    category_id bigint NOT NULL REFERENCES categories,
    list_price numeric(14, 2) NOT NULL CHECK (
        list_price >= 0 AND list_price <> 'NaN'::numeric
    )
);

CREATE TABLE product_suppliers (
    product_id bigint REFERENCES products,
    supplier_id bigint REFERENCES suppliers,
    PRIMARY KEY (product_id, supplier_id)
);

CREATE TABLE warehouses (
    warehouse_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code text NOT NULL UNIQUE CHECK (btrim(code) <> '')
);

CREATE TABLE inventory_positions (
    warehouse_id bigint REFERENCES warehouses,
    product_id bigint REFERENCES products,
    PRIMARY KEY (warehouse_id, product_id)
);

CREATE TABLE sales_orders (
    order_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    customer_id bigint NOT NULL REFERENCES customers,
    ordered_at timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE order_items (
    order_id bigint REFERENCES sales_orders,
    line_number integer CHECK (line_number > 0),
    product_id bigint NOT NULL REFERENCES products,
    quantity integer NOT NULL CHECK (quantity > 0),
    unit_price numeric(14, 2) NOT NULL CHECK (
        unit_price >= 0 AND unit_price <> 'NaN'::numeric
    ),
    PRIMARY KEY (order_id, line_number)
);

CREATE TABLE payments (
    payment_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id bigint NOT NULL REFERENCES sales_orders,
    reference text NOT NULL UNIQUE CHECK (btrim(reference) <> ''),
    amount numeric(14, 2) NOT NULL CHECK (amount > 0 AND amount <> 'NaN'::numeric),
    paid_at timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE stock_movements (
    movement_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    warehouse_id bigint NOT NULL,
    product_id bigint NOT NULL,
    movement_type text NOT NULL,
    quantity_delta integer NOT NULL,
    occurred_at timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP,
    FOREIGN KEY (warehouse_id, product_id) REFERENCES inventory_positions,
    CONSTRAINT stock_movement_direction CHECK (
        (movement_type = 'receipt' AND quantity_delta > 0)
        OR (movement_type = 'shipment' AND quantity_delta < 0)
        OR (movement_type = 'adjustment' AND quantity_delta <> 0)
    )
);

CREATE INDEX products_category_idx ON products (category_id);
CREATE INDEX product_suppliers_supplier_idx ON product_suppliers (supplier_id);
CREATE INDEX inventory_positions_product_idx ON inventory_positions (product_id);
CREATE INDEX sales_orders_customer_date_idx ON sales_orders (customer_id, ordered_at);
CREATE INDEX order_items_product_idx ON order_items (product_id);
CREATE INDEX payments_order_idx ON payments (order_id);
CREATE INDEX stock_movements_position_date_idx
    ON stock_movements (warehouse_id, product_id, occurred_at);

CREATE VIEW inventory_balances AS
SELECT position.warehouse_id, position.product_id,
       COALESCE(SUM(movement.quantity_delta), 0) AS quantity_on_hand
FROM inventory_positions AS position
LEFT JOIN stock_movements AS movement USING (warehouse_id, product_id)
GROUP BY position.warehouse_id, position.product_id;

CREATE VIEW order_balances AS
WITH item_totals AS (
    SELECT order_id, SUM(quantity * unit_price) AS order_total
    FROM order_items
    GROUP BY order_id
), payment_totals AS (
    SELECT order_id, SUM(amount) AS paid_total
    FROM payments
    GROUP BY order_id
)
SELECT orders.order_id,
       COALESCE(items.order_total, 0) AS order_total,
       COALESCE(payments.paid_total, 0) AS paid_total,
       COALESCE(items.order_total, 0) - COALESCE(payments.paid_total, 0)
           AS outstanding_balance
FROM sales_orders AS orders
LEFT JOIN item_totals AS items USING (order_id)
LEFT JOIN payment_totals AS payments USING (order_id);

COMMIT;
